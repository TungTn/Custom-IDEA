use std::fs;
use std::path::Path;
use ts_rs::{Config, TS};

use ide_vfs::{FileNodeDto, SearchFileResultDto, SearchTextResultDto, VfsChangeEventDto};
use ide_terminal::AvailableShell;
use ide_run::{ProcessOutputPayload, ProcessExitPayload, BuildCommandResult, ToolchainInfo, JdkItemDto};
use ide_vcs::{GitFileChangeDto, GitStatusDto, GitCommitItemDto, GitCommitDetailsDto, GitBlameLineDto, GitBranchInfoDto, GitStashItemDto};
use ide_db::{DbColumnDto, DbIndexDto, DbTableDto, DbSchemaDto, DbQueryResultDto, DbTestConnectionResultDto};
use ide_http::{HttpRequestDto, HttpResponseDto, HttpBlockDto};

#[test]
fn export_all_bindings() {
    let cfg = Config::default();

    let mut output = String::new();
    output.push_str("// ========================================================\n");
    output.push_str("// This file is AUTO-GENERATED by ts-rs from Rust backend DTOs.\n");
    output.push_str("// DO NOT EDIT DIRECTLY. Run `npm run gen:bindings` to update.\n");
    output.push_str("// ========================================================\n\n");

    let types: Vec<(&str, String)> = vec![
        // ─── ide-vfs ───
        ("FileNodeDto", FileNodeDto::decl(&cfg)),
        ("SearchFileResultDto", SearchFileResultDto::decl(&cfg)),
        ("SearchTextResultDto", SearchTextResultDto::decl(&cfg)),
        ("VfsChangeEventDto", VfsChangeEventDto::decl(&cfg)),

        // ─── ide-terminal ───
        ("AvailableShell", AvailableShell::decl(&cfg)),

        // ─── ide-run ───
        ("ProcessOutputPayload", ProcessOutputPayload::decl(&cfg)),
        ("ProcessExitPayload", ProcessExitPayload::decl(&cfg)),
        ("BuildCommandResult", BuildCommandResult::decl(&cfg)),
        ("ToolchainInfo", ToolchainInfo::decl(&cfg)),
        ("JdkItemDto", JdkItemDto::decl(&cfg)),

        // ─── ide-vcs ───
        ("GitFileChangeDto", GitFileChangeDto::decl(&cfg)),
        ("GitStatusDto", GitStatusDto::decl(&cfg)),
        ("GitCommitItemDto", GitCommitItemDto::decl(&cfg)),
        ("GitCommitDetailsDto", GitCommitDetailsDto::decl(&cfg)),
        ("GitBlameLineDto", GitBlameLineDto::decl(&cfg)),
        ("GitBranchInfoDto", GitBranchInfoDto::decl(&cfg)),
        ("GitStashItemDto", GitStashItemDto::decl(&cfg)),

        // ─── ide-db ───
        ("DbColumnDto", DbColumnDto::decl(&cfg)),
        ("DbIndexDto", DbIndexDto::decl(&cfg)),
        ("DbTableDto", DbTableDto::decl(&cfg)),
        ("DbSchemaDto", DbSchemaDto::decl(&cfg)),
        ("DbQueryResultDto", DbQueryResultDto::decl(&cfg)),
        ("DbTestConnectionResultDto", DbTestConnectionResultDto::decl(&cfg)),

        // ─── ide-http ───
        ("HttpRequestDto", HttpRequestDto::decl(&cfg)),
        ("HttpResponseDto", HttpResponseDto::decl(&cfg)),
        ("HttpBlockDto", HttpBlockDto::decl(&cfg)),
    ];

    for (_name, decl) in types {
        output.push_str("export ");
        output.push_str(&decl);
        output.push_str("\n\n");
    }

    let target_path = Path::new("../src/bindings.ts");
    if let Err(_) = fs::write(target_path, output.as_bytes()) {
        let tmp = Path::new("../src/bindings.ts.tmp");
        if fs::write(&tmp, output.as_bytes()).is_ok() {
            let _ = fs::rename(&tmp, target_path);
        }
    }
    println!("Successfully exported TypeScript bindings to ../src/bindings.ts");
}
